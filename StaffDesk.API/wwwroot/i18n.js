function translatePhrase(english) {
    if (english == null) return '';
    const s = String(english).trim();
    const key = I18N_PHRASE_KEYS[s];
    if (key) return t(key);
    return s;
}

/** Walk the DOM and replace exact English UI phrases with the active language. */
function localizeTree(root) {
    const scope = root || document.body;
    if (!scope) return;

    const walk = (node) => {
        if (!node) return;
        if (node.nodeType === 3) {
            const raw = node.nodeValue;
            if (!raw || !raw.trim()) return;
            const trimmed = raw.trim();
            const key = I18N_PHRASE_KEYS[trimmed];
            if (!key) return;
            const translated = t(key);
            if (translated !== trimmed) {
                node.nodeValue = raw.replace(trimmed, translated);
            }
            return;
        }
        if (node.nodeType !== 1) return;
        const tag = node.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA') return;

        if (node.placeholder) {
            const pk = I18N_PHRASE_KEYS[node.placeholder.trim()];
            if (pk) node.placeholder = t(pk);
        }
        if (node.title) {
            const tk = I18N_PHRASE_KEYS[node.title.trim()];
            if (tk) node.title = t(tk);
        }
        const aria = node.getAttribute && node.getAttribute('aria-label');
        if (aria) {
            const ak = I18N_PHRASE_KEYS[aria.trim()];
            if (ak) node.setAttribute('aria-label', t(ak));
        }

        // Prefer data-i18n when present (already handled by applyI18n)
        if (node.hasAttribute && node.hasAttribute('data-i18n')) {
            // still walk children for mixed content? skip text children by walking all
        }

        const children = node.childNodes;
        for (let i = 0; i < children.length; i++) walk(children[i]);
    };

    walk(scope);
}

function scheduleLocalize(root) {
    const run = () => localizeTree(root || document.body);
    if (typeof requestAnimationFrame === 'function') {
        requestAnimationFrame(() => requestAnimationFrame(run));
    } else {
        setTimeout(run, 0);
    }
}

window.translatePhrase = translatePhrase;
window.localizeTree = localizeTree;
window.scheduleLocalize = scheduleLocalize;

