function getStoredLang() {
    try {
        return localStorage.getItem('lang') === 'ar' ? 'ar' : 'en';
    } catch (e) {
        return 'en';
    }
}

function t(key, vars) {
    const lang = getStoredLang();
    const table = I18N_STRINGS[lang] || I18N_STRINGS.en;
    let text = table[key] ?? I18N_STRINGS.en[key] ?? key;
    if (vars && typeof vars === 'object') {
        Object.keys(vars).forEach(k => {
            text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
        });
    }
    return text;
}

function translateRole(role) {
    const raw = (role || 'Member').replace(/\s+/g, '_');
    const key = 'role.' + raw;
    if (I18N_STRINGS.en[key] || I18N_STRINGS.ar[key]) return t(key);
    return (role || t('common.member')).replace(/_/g, ' ');
}

function translateStatus(status) {
    if (!status) return '';
    const key = 'status.' + String(status).toUpperCase().replace(/\s+/g, '_');
    return I18N_STRINGS.en[key] ? t(key) : String(status).replace(/_/g, ' ');
}

function translatePriority(priority) {
    if (!priority) return '';
    const key = 'priority.' + String(priority).toUpperCase();
    return I18N_STRINGS.en[key] ? t(key) : String(priority);
}

function localeTag() {
    return getStoredLang() === 'ar' ? 'ar' : 'en';
}

function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key) return;
        const attr = el.getAttribute('data-i18n-attr');
        const value = t(key);
        if (attr) {
            el.setAttribute(attr, value);
        } else {
            el.textContent = value;
        }
    });

    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });

    scope.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });

    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });

    scope.querySelectorAll('[data-i18n-html]').forEach(el => {
        el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });

    if (document.title !== undefined) {
        const titleKey = document.body?.getAttribute('data-i18n-doc-title') || 'doc.title';
        if (I18N_STRINGS.en[titleKey]) document.title = t(titleKey);
    }

    syncLanguageButtons();
    scheduleLocalize(scope === document ? document.body : scope);
}

function syncLanguageButtons() {
    const lang = getStoredLang();
    document.querySelectorAll('[data-lang-option]').forEach(btn => {
        const opt = btn.getAttribute('data-lang-option');
        btn.classList.toggle('active', opt === lang);
        btn.setAttribute('aria-pressed', opt === lang ? 'true' : 'false');
    });
}

function setLanguage(lang, options) {
    const next = lang === 'ar' ? 'ar' : 'en';
    try {
        localStorage.setItem('lang', next);
    } catch (e) { /* ignore */ }

    document.documentElement.setAttribute('lang', next);
    document.documentElement.setAttribute('dir', next === 'ar' ? 'rtl' : 'ltr');

    applyI18n(document);

    if (typeof applyTheme === 'function') {
        applyTheme(typeof getStoredTheme === 'function' ? getStoredTheme() : 'light');
    }

    const userRole = document.getElementById('user-role');
    if (userRole) {
        userRole.textContent = translateRole(localStorage.getItem('role'));
    }

    if (options && options.reloadView === false) {
        scheduleLocalize(document.body);
        return;
    }

    try {
        const hash = window.location.hash || '';
        if (typeof HASH_ROUTES !== 'undefined' && HASH_ROUTES[hash]) {
            HASH_ROUTES[hash]();
        } else if (typeof currentView !== 'undefined' && currentView === 'profile' && typeof renderProfile === 'function') {
            renderProfile();
        }
    } catch (e) {
        console.warn('i18n view refresh failed', e);
    }
    scheduleLocalize(document.body);
}

